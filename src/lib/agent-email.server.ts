/**
 * Structured incident / medical handoff emails for Allma agent tools.
 * Uses Resend when RESEND_API_KEY is set; otherwise returns a clear not-configured result
 * (never pretends mail was sent).
 */
import { createServerFn } from "@tanstack/react-start";
import { z } from "zod";

function runtimeEnv(name: string): string {
  const fromProcess = (process.env[name] || "").trim();
  if (fromProcess) return fromProcess;
  const cf = (globalThis as { __env__?: Record<string, unknown> }).__env__;
  const fromCf = cf?.[name];
  return typeof fromCf === "string" ? fromCf.trim() : "";
}

export type IncidentEmailInput = {
  to: string;
  subject: string;
  incidentType: "medical" | "security" | "accident" | "general";
  patientOrReporterName: string;
  locationSummary: string;
  triageSummary: string;
  actionsTaken: string[];
  status: "active" | "stabilized" | "resolved";
  coordinates?: { lat: number; lng: number } | null;
};

export type IncidentEmailResult = {
  success: boolean;
  messageId: string | null;
  timestamp: string;
  error?: string;
  previewSubject?: string;
  previewTo?: string;
};

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

export function isEmailDispatchConfigured() {
  return Boolean(runtimeEnv("RESEND_API_KEY"));
}

export function buildIncidentEmailHtml(input: IncidentEmailInput, timestamp: string): string {
  const actions = (input.actionsTaken || [])
    .map((a) => String(a).trim())
    .filter(Boolean)
    .map((a) => `<li>${escapeHtml(a)}</li>`)
    .join("");
  const coords =
    input.coordinates &&
    Number.isFinite(input.coordinates.lat) &&
    Number.isFinite(input.coordinates.lng)
      ? `${input.coordinates.lat.toFixed(5)}, ${input.coordinates.lng.toFixed(5)}`
      : "Not shared";

  return `<!DOCTYPE html><html><body style="font-family:system-ui,sans-serif;color:#111;line-height:1.45">
  <h1 style="font-size:18px;margin:0 0 12px">Allma Safety AI — Incident handoff</h1>
  <p style="margin:0 0 8px"><strong>Time (UTC):</strong> ${escapeHtml(timestamp)}</p>
  <p style="margin:0 0 8px"><strong>Type:</strong> ${escapeHtml(input.incidentType)}</p>
  <p style="margin:0 0 8px"><strong>Status:</strong> ${escapeHtml(input.status)}</p>
  <p style="margin:0 0 8px"><strong>Person:</strong> ${escapeHtml(input.patientOrReporterName)}</p>
  <p style="margin:0 0 8px"><strong>Location:</strong> ${escapeHtml(input.locationSummary)}</p>
  <p style="margin:0 0 8px"><strong>Coordinates:</strong> ${escapeHtml(coords)}</p>
  <h2 style="font-size:15px;margin:16px 0 8px">Triage / situation</h2>
  <p style="margin:0 0 12px;white-space:pre-wrap">${escapeHtml(input.triageSummary)}</p>
  <h2 style="font-size:15px;margin:16px 0 8px">Actions already taken</h2>
  ${actions ? `<ul style="margin:0;padding-left:18px">${actions}</ul>` : "<p>None listed.</p>"}
  <p style="margin:20px 0 0;font-size:12px;color:#555">Generated by Allma Safety AI. This is a handoff note — it does not mean police or ambulance were automatically dispatched.</p>
</body></html>`;
}

function escapeHtml(value: string) {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export async function sendIncidentEmail(input: IncidentEmailInput): Promise<IncidentEmailResult> {
  const timestamp = new Date().toISOString();
  const to = input.to.trim();
  if (!EMAIL_RE.test(to)) {
    return { success: false, messageId: null, timestamp, error: "invalid_recipient" };
  }
  const apiKey = runtimeEnv("RESEND_API_KEY");
  if (!apiKey) {
    return {
      success: false,
      messageId: null,
      timestamp,
      error: "email_not_configured",
      previewSubject: input.subject,
      previewTo: to,
    };
  }

  const from =
    runtimeEnv("RESEND_FROM_EMAIL") || "Allma Safety AI <alerts@allmasafetyai.online>";
  const html = buildIncidentEmailHtml(input, timestamp);
  const text = [
    `Allma Safety AI incident handoff (${timestamp})`,
    `Type: ${input.incidentType}`,
    `Status: ${input.status}`,
    `Person: ${input.patientOrReporterName}`,
    `Location: ${input.locationSummary}`,
    `Triage: ${input.triageSummary}`,
    `Actions: ${(input.actionsTaken || []).join("; ") || "None"}`,
  ].join("\n");

  const res = await fetch("https://api.resend.com/emails", {
    method: "POST",
    headers: {
      Authorization: `Bearer ${apiKey}`,
      "Content-Type": "application/json",
    },
    body: JSON.stringify({
      from,
      to: [to],
      subject: input.subject.slice(0, 200),
      html,
      text,
    }),
  });

  const bodyText = await res.text();
  if (!res.ok) {
    console.error("[agent-email] resend failed", res.status, bodyText.slice(0, 300));
    return {
      success: false,
      messageId: null,
      timestamp,
      error: `resend_${res.status}`,
      previewSubject: input.subject,
      previewTo: to,
    };
  }

  let messageId: string | null = null;
  try {
    const json = JSON.parse(bodyText) as { id?: string };
    messageId = json.id ?? null;
  } catch {
    messageId = `resend-${Date.now()}`;
  }

  return {
    success: true,
    messageId,
    timestamp,
    previewSubject: input.subject,
    previewTo: to,
  };
}

/** Plain-text message from Allma's own sender (used when the user has no Gmail connected). */
export async function sendSystemTextEmail(input: {
  to: string;
  subject: string;
  text: string;
  replyTo?: string | null;
}): Promise<{ success: boolean; messageId: string | null; error?: string }> {
  const to = input.to.trim();
  if (!EMAIL_RE.test(to)) return { success: false, messageId: null, error: "invalid_recipient" };
  const apiKey = runtimeEnv("RESEND_API_KEY");
  if (!apiKey) return { success: false, messageId: null, error: "email_not_configured" };
  const from = runtimeEnv("RESEND_FROM_EMAIL") || "Allma Safety AI <alerts@allmasafetyai.online>";
  const replyTo = input.replyTo && EMAIL_RE.test(input.replyTo.trim()) ? [input.replyTo.trim()] : undefined;
  try {
    const res = await fetch("https://api.resend.com/emails", {
      method: "POST",
      headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
      body: JSON.stringify({
        from,
        to: [to],
        subject: input.subject.replace(/[\r\n]+/g, " ").slice(0, 200),
        text: input.text,
        ...(replyTo ? { reply_to: replyTo } : {}),
      }),
    });
    const bodyText = await res.text();
    if (!res.ok) {
      console.error("[agent-email] resend failed", res.status);
      return { success: false, messageId: null, error: `resend_${res.status}` };
    }
    let messageId: string | null = null;
    try {
      messageId = (JSON.parse(bodyText) as { id?: string }).id ?? null;
    } catch {
      messageId = null;
    }
    return { success: true, messageId };
  } catch {
    return { success: false, messageId: null, error: "resend_unreachable" };
  }
}

const incidentEmailSchema = z.object({
  to: z.string().email().max(200),
  subject: z.string().min(1).max(200),
  incidentType: z.enum(["medical", "security", "accident", "general"]),
  patientOrReporterName: z.string().min(1).max(120),
  locationSummary: z.string().min(1).max(400),
  triageSummary: z.string().min(1).max(2000),
  actionsTaken: z.array(z.string().max(200)).max(20).default([]),
  status: z.enum(["active", "stabilized", "resolved"]),
  coordinates: z
    .object({
      lat: z.number().min(-90).max(90),
      lng: z.number().min(-180).max(180),
    })
    .nullable()
    .optional(),
});

/** TanStack Start server function — same payload the agent tool uses. */
export const sendIncidentEmailFn = createServerFn({ method: "POST" })
  .validator((input) => incidentEmailSchema.parse(input))
  .handler(async ({ data }) => sendIncidentEmail(data));
