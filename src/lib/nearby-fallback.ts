function distanceBetween(a: { lat: number; lng: number }, b: { lat: number; lng: number }) {
  const radians = (value: number) => (value * Math.PI) / 180;
  const deltaLat = radians(b.lat - a.lat);
  const deltaLng = radians(b.lng - a.lng);
  const haversine =
    Math.sin(deltaLat / 2) ** 2 +
    Math.cos(radians(a.lat)) * Math.cos(radians(b.lat)) * Math.sin(deltaLng / 2) ** 2;
  return 6_371_000 * 2 * Math.atan2(Math.sqrt(haversine), Math.sqrt(1 - haversine));
}

export function getSeededNearbyFacilities(
  center: { lat: number; lng: number },
  radiusMeters = 10_000,
): NearbyPlace[] {
  return SEEDED_FACILITIES.map((facility) => ({
    ...facility,
    distance_m: distanceBetween(center, { lat: facility.latitude, lng: facility.longitude }),
  }))
    .filter((facility) => facility.distance_m <= radiusMeters)
    .sort((a, b) => a.distance_m - b.distance_m);
}
